// Pure helpers for mount-patterns.mjs (no I/O — unit tested).

const COMPONENT_ALIAS_IMPORT =
  /import\s+(?:[^"']*?\s+from\s+)?["']@\/(?:components|lib|hooks)\/([^"']+)["']/g;

const dedupe = (arr) => [...new Set(arr)];

/** Trailing names of imports from @/components, @/lib, @/hooks (first-seen order). */
export function deriveComponentsFromSource(source) {
  const names = [];
  for (const m of String(source).matchAll(COMPONENT_ALIAS_IMPORT)) {
    const trailing = m[1].split("/").pop();
    if (trailing) names.push(trailing);
  }
  return dedupe(names);
}

/** Keep only derived names that exist in the installed inventory (when known). */
export function confirmComponents(derived, installedBasenames) {
  if (!installedBasenames || installedBasenames.length === 0) return derived;
  const set = new Set(installedBasenames);
  return derived.filter((n) => set.has(n));
}

/** Apply pattern.json `components` override: array replaces; {add,remove} adjusts. */
export function applyComponentsOverride(list, override) {
  if (override === undefined || override === null) return list;
  if (Array.isArray(override)) return [...override];
  const add = override.add ?? [];
  const remove = new Set(override.remove ?? []);
  return dedupe([...list, ...add]).filter((n) => !remove.has(n));
}

/** Full resolution: derive -> confirm against installed -> apply override. */
export function resolveComponents({ source, installedBasenames, override }) {
  return applyComponentsOverride(
    confirmComponents(deriveComponentsFromSource(source), installedBasenames),
    override,
  );
}

/**
 * Private search/index facets for a pattern. Known keys (keywords,
 * categories) default to []; any extra authored keys pass through unchanged.
 * Never sent to a model.
 */
export function resolveInternal(internal) {
  const i = internal ?? {};
  return { ...i, keywords: i.keywords ?? [], categories: i.categories ?? [] };
}

/** Preview frame size for a pattern; fills/validates each axis (default 400x300). */
export function resolveDimensions(d) {
  const w = Number(d?.width);
  const h = Number(d?.height);
  return {
    width: Number.isFinite(w) && w > 0 ? w : 400,
    height: Number.isFinite(h) && h > 0 ? h : 300,
  };
}

export const GENERATED_MARKER = "GENERATED by mount-patterns.mjs";

/** Route path for a pattern folder name. */
export function routeFor(name) {
  return `/${name}`;
}

/** Server-component route that renders a pattern's default export. */
export function renderPatternPage(name) {
  const importPath = `@/patterns/${name}/${name}`;
  return `// ${GENERATED_MARKER} — do not edit. Source: patterns/${name}/${name}.tsx
import Pattern from ${JSON.stringify(importPath)};

export default function Page() {
  return (
    <main className="flex min-h-svh items-center justify-center p-6">
      <Pattern />
    </main>
  );
}
`;
}

/** Index route listing every pattern. Strings are JSON-escaped into JSX exprs. */
export function renderIndexPage(registryName, entries) {
  const items = entries
    .map(
      (e) =>
        `        <li className="rounded-md border p-4">\n` +
        `          <Link href={${JSON.stringify(e.route)}} className="font-medium underline">{${JSON.stringify(e.title)}}</Link>\n` +
        `          <p className="text-sm text-muted-foreground">{${JSON.stringify(e.description ?? "")}}</p>\n` +
        `        </li>`,
    )
    .join("\n");
  return `// ${GENERATED_MARKER} — do not edit.
import Link from "next/link";

export default function Page() {
  return (
    <main className="mx-auto max-w-2xl p-8">
      <h1 className="mb-6 text-2xl font-bold">{${JSON.stringify(`${registryName} patterns`)}}</h1>
      <ul className="space-y-3">
${items}
      </ul>
    </main>
  );
}
`;
}

/** Per-registry search manifest the future gallery globs. */
export function buildManifest(registryName, entries) {
  return { registry: registryName, patterns: entries };
}

/**
 * Aggregate per-registry manifests into the gallery catalog.
 * sites: [{ slug, manifest }] where manifest = parsed patterns/manifest.json.
 */
export function buildCatalog(sites) {
  const registries = [];
  const categorySet = new Set();
  const patterns = [];
  for (const { slug, manifest } of sites) {
    const registry = manifest.registry;
    registries.push({ id: registry, slug, count: manifest.patterns.length });
    for (const p of manifest.patterns) {
      const categories = p.internal?.categories ?? [];
      categories.forEach((c) => categorySet.add(c));
      patterns.push({
        registry,
        slug,
        name: p.name,
        title: p.title ?? p.name,
        iframeSrc: `/sites/${slug}/${p.name}/index.html`,
        dimensions: resolveDimensions(p.dimensions),
        categories,
      });
    }
  }
  return { registries, categories: [...categorySet].sort(), patterns };
}
