import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { mountPatterns } from "./mount-patterns.mjs";

function makeSite() {
  const siteDir = mkdtempSync(join(tmpdir(), "site-"));
  mkdirSync(join(siteDir, "app"), { recursive: true });
  // installed components inventory
  mkdirSync(join(siteDir, "components", "ui", "8bit"), { recursive: true });
  for (const c of ["button", "card"]) {
    writeFileSync(join(siteDir, "components", "ui", "8bit", `${c}.tsx`), "export const x = 1;\n");
  }
  // authored pattern
  mkdirSync(join(siteDir, "patterns", "login-card"), { recursive: true });
  writeFileSync(
    join(siteDir, "patterns", "login-card", "login-card.tsx"),
    `import { Button } from "@/components/ui/8bit/button";
import { Card } from "@/components/ui/8bit/card";
import { cn } from "@/lib/utils";
export default function LoginCard() { return <Card><Button>Go</Button></Card>; }
`,
  );
  writeFileSync(
    join(siteDir, "patterns", "login-card", "pattern.json"),
    JSON.stringify({
      title: "Login card",
      description: "demo",
      components: { add: ["input"] },
      internal: { keywords: ["login"], categories: ["forms"] },
      llm: { summary: "local-state login", source: "https://example.com/login-card.tsx" },
    }) + "\n",
  );
  // a stale generated route to be pruned
  mkdirSync(join(siteDir, "app", "old"), { recursive: true });
  writeFileSync(join(siteDir, "app", "old", "page.tsx"), "// GENERATED by mount-patterns.mjs\nexport default () => null;\n");
  return siteDir;
}

test("mountPatterns writes route, index, manifest; resolves components; prunes stale", () => {
  const siteDir = makeSite();
  const { patterns } = mountPatterns({ siteDir, registryName: "@8bitcn" });

  assert.ok(existsSync(join(siteDir, "app", "login-card", "page.tsx")));
  assert.ok(
    readFileSync(join(siteDir, "app", "login-card", "page.tsx"), "utf8").includes("GENERATED by mount-patterns.mjs"),
    "generated route carries the marker",
  );
  assert.ok(existsSync(join(siteDir, "app", "page.tsx")));
  assert.equal(existsSync(join(siteDir, "app", "old")), false, "stale marked route pruned");

  const manifest = JSON.parse(readFileSync(join(siteDir, "patterns", "manifest.json"), "utf8"));
  assert.equal(manifest.registry, "@8bitcn");
  assert.equal(manifest.patterns.length, 1);
  const p = manifest.patterns[0];
  assert.equal(p.name, "login-card");
  assert.equal(p.route, "/login-card");
  assert.deepEqual(p.components, ["button", "card", "input"]); // derived [button,card] (+utils dropped) + add input
  assert.deepEqual(p.dimensions, { width: 400, height: 300 }); // default (pattern.json has no dimensions)
  assert.deepEqual(p.internal, { keywords: ["login"], categories: ["forms"] });
  assert.deepEqual(p.llm, { summary: "local-state login", source: "https://example.com/login-card.tsx" });
  assert.equal(p.keywords, undefined, "keywords no longer top-level");
  assert.equal(p.categories, undefined, "categories no longer top-level");
  assert.deepEqual(patterns, manifest.patterns);
});

test("mountPatterns defaults internal/llm when a pattern has no pattern.json", () => {
  const siteDir = mkdtempSync(join(tmpdir(), "site-"));
  mkdirSync(join(siteDir, "app"), { recursive: true });
  mkdirSync(join(siteDir, "patterns", "bare"), { recursive: true });
  writeFileSync(
    join(siteDir, "patterns", "bare", "bare.tsx"),
    `import { Button } from "@/components/ui/8bit/button";
export default function Bare() { return <Button>Hi</Button>; }
`,
  );

  const { patterns } = mountPatterns({ siteDir, registryName: "@8bitcn" });
  const p = patterns[0];
  assert.equal(p.name, "bare");
  assert.deepEqual(p.internal, { keywords: [], categories: [] });
  assert.deepEqual(p.llm, {});
  assert.deepEqual(p.components, ["button"]); // derived; no components/ inventory => pass-through
});

test("mountPatterns carries authored dimensions from pattern.json", () => {
  const siteDir = mkdtempSync(join(tmpdir(), "site-"));
  mkdirSync(join(siteDir, "app"), { recursive: true });
  mkdirSync(join(siteDir, "patterns", "wide"), { recursive: true });
  writeFileSync(
    join(siteDir, "patterns", "wide", "wide.tsx"),
    `import { Button } from "@/components/ui/8bit/button";
export default function Wide() { return <Button>Hi</Button>; }
`,
  );
  writeFileSync(
    join(siteDir, "patterns", "wide", "pattern.json"),
    JSON.stringify({ dimensions: { width: 720, height: 480 } }) + "\n",
  );
  const { patterns } = mountPatterns({ siteDir, registryName: "@8bitcn" });
  assert.deepEqual(patterns[0].dimensions, { width: 720, height: 480 });
});
